"""Generate fictional demo text with the real, side-effect-free card renderer."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
import progress_card

base = dict(project='demo-web', title='检查页面布局', thread='demo0001',
            state='running', started=100, finished=None)
cards = [progress_card.render(dict(base, detail=detail), now=now)
         for now, detail in [(105, '正在检查页面布局和按钮状态。'),
                             (117, '已核对布局，正在运行检查并准备截图。')]]
cards.append(progress_card.render(dict(base, state='ended', finished=135,
                                      detail='本轮已结束，完整答复和截图另行交付。')))
Path(__file__).with_name('cards.js').write_text(
    '/* Fictional fixtures; generated by render.py, never read from live state. */\n'
    + 'window.DEMO_CARDS = ' + json.dumps(cards, ensure_ascii=False, indent=2) + ';\n')
